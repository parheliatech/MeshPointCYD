// Returns a readable name for a numeric model string ("9" -> "RAK4631"), else the input.
inline const char* hwModelName(const char* model) {
    if (!model || !*model) return model;
    char* end;
    long id = strtol(model, &end, 10);
    if (*end != 0) return model;  // already a name
    for (const HwName& h : kHwNames) {
        if (h.id == id) return h.name;
    }
    return model;
}
